// 103 · Depth of a Tree
import assert from "node:assert/strict";

export class TreeNode {
  val: number;
  left: TreeNode | null;
  right: TreeNode | null;

  constructor(val: number, left: TreeNode | null = null, right: TreeNode | null = null) {
    this.val = val;
    this.left = left;
    this.right = right;
  }
}

export function maxDepth(root: TreeNode | null): number {
  if (root === null) return 0;
  return 1 + Math.max(maxDepth(root.left), maxDepth(root.right));
}

function fromLevelOrder(values: (number | null)[]): TreeNode | null {
  if (values.length === 0 || values[0] === null) return null;
  const root = new TreeNode(values[0]);
  const queue = [root];
  let head = 0;
  for (let i = 1; i < values.length; i += 2) {
    const node = queue[head++];
    const left = values[i];
    const right = i + 1 < values.length ? values[i + 1] : null;
    if (left !== null) {
      node.left = new TreeNode(left);
      queue.push(node.left);
    }
    if (right !== null) {
      node.right = new TreeNode(right);
      queue.push(node.right);
    }
  }
  return root;
}

assert.equal(maxDepth(fromLevelOrder([5, 2, 9, null, 4, 7, null, null, null, 6])), 4);
assert.equal(maxDepth(fromLevelOrder([1, null, 2, null, 3])), 3);
assert.equal(maxDepth(fromLevelOrder([])), 0);
assert.equal(maxDepth(fromLevelOrder([42])), 1);
assert.equal(maxDepth(fromLevelOrder([1, 2, 3])), 2);
